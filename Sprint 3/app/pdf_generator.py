from pathlib import Path
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas
import qrcode

OUTPUT_DIR = Path(__file__).resolve().parent.parent / "generated_invoices"
OUTPUT_DIR.mkdir(exist_ok=True)

def generate_invoice_pdf(invoice):
    pdf_path = OUTPUT_DIR / f"invoice_{invoice['id']}.pdf"
    qr_path = OUTPUT_DIR / f"upi_qr_{invoice['id']}.png"

    c = canvas.Canvas(str(pdf_path), pagesize=A4)
    width, height = A4

    c.setFont("Helvetica-Bold", 22)
    c.drawString(25*mm, height-30*mm, "ChatBiz")
    c.setFont("Helvetica", 10)
    c.drawString(25*mm, height-37*mm, "AI-Powered Business Management")
    c.setFont("Helvetica-Bold", 16)
    c.drawRightString(width-25*mm, height-30*mm, f"INVOICE #{invoice['id']:04d}")

    y = height - 60*mm
    c.setFont("Helvetica-Bold", 11); c.drawString(25*mm, y, "Bill To")
    c.setFont("Helvetica", 10); c.drawString(25*mm, y-7*mm, invoice["client_name"])
    if invoice.get("client_phone"):
        c.drawString(25*mm, y-14*mm, invoice["client_phone"])
    c.drawString(width-75*mm, y-7*mm, f"Due: {invoice['due_date']}")
    c.drawString(width-75*mm, y-14*mm, f"Status: {invoice['status']}")

    y -= 35*mm
    c.setFont("Helvetica-Bold", 11)
    c.drawString(25*mm, y, "Description")
    c.drawRightString(width-25*mm, y, "Amount")
    c.line(25*mm, y-3*mm, width-25*mm, y-3*mm)
    y -= 12*mm
    c.setFont("Helvetica", 10)
    c.drawString(25*mm, y, invoice["description"])
    c.drawRightString(width-25*mm, y, f"Rs. {invoice['amount']:,.2f}")
    y -= 18*mm
    c.setFont("Helvetica-Bold", 12)
    c.drawString(25*mm, y, "TOTAL")
    c.drawRightString(width-25*mm, y, f"Rs. {invoice['amount']:,.2f}")

    if invoice.get("upi_id"):
        upi = f"upi://pay?pa={invoice['upi_id']}&pn=ChatBiz&am={invoice['amount']:.2f}&cu=INR"
        qrcode.make(upi).save(qr_path)
        c.drawImage(str(qr_path), 25*mm, 35*mm, width=35*mm, height=35*mm)
        c.setFont("Helvetica", 9)
        c.drawString(65*mm, 50*mm, "Scan to pay using UPI")
        c.drawString(65*mm, 43*mm, invoice["upi_id"])

    c.setFont("Helvetica", 8)
    c.drawString(25*mm, 20*mm, "Generated by ChatBiz — Sprint 3 demo")
    c.save()
    return pdf_path
